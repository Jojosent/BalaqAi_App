import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { createHandler } from '../app.js';
const fixture = { profile: { name: 'Test', birthday: '', city: '' }, stage: null, pregnancyStart: null, pregnancyNotes: { doctor: '', notes: '' }, checklist: [], trackingFolate: false };
test('API enforces identity, validation and per-user storage', async t => {
  const docs = new Map();
  const database = { collection: name => { assert.equal(name, 'users'); return { doc: uid => ({ get: async () => ({ exists: docs.has(uid), data: () => docs.get(uid) }), set: async data => docs.set(uid, data) }) }; } };
  const auth = { verifyIdToken: async (token, revoked) => { assert.equal(revoked, true); if (token === 'bad') throw new Error('Invalid'); return { uid: token, email_verified: token !== 'unverified' }; } };
  const server = createServer(createHandler({ auth, database }));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (token, method = 'GET', body, extra = {}) => fetch(`${base}/v1/me`, { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), 'Content-Type': 'application/json', ...extra }, body: body === undefined ? undefined : JSON.stringify(body) });
  assert.equal((await call()).status, 401);
  assert.equal((await call('bad')).status, 401);
  assert.equal((await call('unverified')).status, 403);
  assert.equal((await call('a', 'GET', undefined, { Origin: 'https://evil.example' })).status, 403);
  assert.equal((await call('a', 'PUT', { ...fixture, uid: 'b' })).status, 400);
  assert.equal((await call('a', 'PUT', { ...fixture, profile: { ...fixture.profile, name: 5 } })).status, 400);
  assert.equal((await call('a', 'PUT', { ...fixture, profile: { ...fixture.profile, birthday: '31.02.1998' } })).status, 400);
  assert.equal((await call('a', 'PUT', { ...fixture, pregnancyStart: '2026-02-31' })).status, 400);
  assert.equal((await call('a', 'PUT', { ...fixture, pregnancyNotes: { doctor: '', notes: 'x'.repeat(1001) } })).status, 400);
  assert.equal((await call('a', 'PUT', fixture)).status, 200);
  assert.deepEqual((await (await call('a')).json()).data, fixture);
  assert.equal((await (await call('b')).json()).data, null);
  assert.equal((await call('a', 'PUT', { ...fixture, profile: { ...fixture.profile, name: 'x'.repeat(20_000) } })).status, 413);
  const malformed = await fetch(`${base}/v1/me`, { method: 'PUT', headers: { Authorization: 'Bearer a', 'Content-Type': 'application/json' }, body: '{' });
  assert.equal(malformed.status, 400);
  assert.equal((await fetch(`${base}/v1/me`, { method: 'POST' })).status, 405);
  assert.equal((await fetch(`${base}/missing`)).status, 404);
});
